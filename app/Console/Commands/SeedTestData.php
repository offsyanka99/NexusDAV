<?php

namespace App\Console\Commands;

use App\Models\User;
use App\Services\Dav\AddressBookBackend;
use App\Services\Dav\CalendarBackend;
use App\Services\Dav\CollectionService;
use Illuminate\Console\Command;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use InvalidArgumentException;

/**
 * Fills one user's new calendar and address book with generated items for the
 * "first sync of a large collection" step of docs/testing/client-checklist.md.
 * Items go through the sabre backends, so sync tokens and the change log are
 * the same as after a client upload. Existing collections are never touched.
 */
class SeedTestData extends Command
{
    protected $signature = 'nexusdav:seed-test-data
        {username : The user who receives the test calendar and address book}
        {--events=5000 : Events to create (0 skips the calendar)}
        {--contacts=2000 : Contacts to create (0 skips the address book)}
        {--calendar=load-test : URI of the new calendar}
        {--address-book=load-test : URI of the new address book}
        {--force : Required. Confirms that thousands of items should be written}';

    protected $description = 'Create a large test calendar and address book for one user (client sync testing)';

    public const MAX_ITEMS = 50000;

    private const BATCH = 250;

    /**
     * A 1x1 PNG, so some contacts carry a photo like a phone's address book.
     */
    private const PHOTO = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGNgYPj/HwADAgH/kpkWGgAAAABJRU5ErkJggg==';

    public function handle(CollectionService $collections): int
    {
        $user = User::query()->where('username', (string) $this->argument('username'))->first();

        if (! $user instanceof User) {
            $this->error('No user named '.$this->argument('username').'.');

            return self::FAILURE;
        }

        $events = $this->count('events');
        $contacts = $this->count('contacts');

        if ($events === null || $contacts === null) {
            return self::FAILURE;
        }

        if ($events === 0 && $contacts === 0) {
            $this->error('Nothing to create: --events and --contacts are both 0.');

            return self::FAILURE;
        }

        $calendarUri = (string) $this->option('calendar');
        $bookUri = (string) $this->option('address-book');

        if (! $this->option('force')) {
            $this->error('This writes '.$events.' events to calendars/'.$user->username.'/'.$calendarUri.'/ and '.$contacts.' contacts to addressbooks/'.$user->username.'/'.$bookUri.'/. Run it again with --force.');

            return self::FAILURE;
        }

        try {
            if ($events > 0) {
                $collections->createCalendar($user, $calendarUri, 'Load test ('.$events.' events)', 'Generated by nexusdav:seed-test-data.', '#7E57C2', false, false);
            }

            if ($contacts > 0) {
                $collections->createAddressBook($user, $bookUri, 'Load test ('.$contacts.' contacts)', 'Generated by nexusdav:seed-test-data.');
            }
        } catch (InvalidArgumentException $exception) {
            $this->error($exception->getMessage().' Delete the old test collection in the admin panel, or choose another URI with --calendar or --address-book.');

            return self::FAILURE;
        }

        if ($events > 0) {
            $this->seedEvents($user, $calendarUri, $events);
        }

        if ($contacts > 0) {
            $this->seedContacts($user, $bookUri, $contacts);
        }

        Log::info('Test data created from the command line', [
            'username' => $user->username,
            'events' => $events,
            'contacts' => $contacts,
        ]);

        if ($events > 0) {
            $this->info('Calendar: /dav/calendars/'.$user->username.'/'.$calendarUri.'/ ('.$events.' events)');

            if (! config('nexusdav.features.caldav')) {
                $this->warn('CalDAV is turned off; clients see the calendar only after it is turned on.');
            }
        }

        if ($contacts > 0) {
            $this->info('Address book: /dav/addressbooks/'.$user->username.'/'.$bookUri.'/ ('.$contacts.' contacts)');

            if (! config('nexusdav.features.carddav')) {
                $this->warn('CardDAV is turned off; clients see the address book only after it is turned on.');
            }
        }

        $this->line('Delete them in the admin panel (Users, then the user) when the test is done.');

        return self::SUCCESS;
    }

    private function count(string $option): ?int
    {
        $raw = (string) $this->option($option);

        if (preg_match('/^\d{1,6}$/', $raw) !== 1 || (int) $raw > self::MAX_ITEMS) {
            $this->error('--'.$option.' must be a whole number from 0 to '.self::MAX_ITEMS.'.');

            return null;
        }

        return (int) $raw;
    }

    private function seedEvents(User $user, string $uri, int $count): void
    {
        $instance = DB::table('calendarinstances')
            ->where('principaluri', $user->principal_uri)
            ->where('uri', $uri)
            ->first(['id', 'calendarid']);
        // sabre identifies a calendar by [calendar id, instance id].
        $calendarId = [(int) $instance?->calendarid, (int) $instance?->id];
        $backend = new CalendarBackend(DB::connection()->getPdo());
        $start = Carbon::now('UTC')->startOfDay()->subDays(365);

        $this->line('Creating '.$count.' events…');
        $bar = $this->output->createProgressBar($count);

        foreach (array_chunk(range(1, $count), self::BATCH) as $batch) {
            DB::transaction(function () use ($batch, $backend, $calendarId, $uri, $start, $count, $bar): void {
                foreach ($batch as $n) {
                    $backend->createCalendarObject($calendarId, $uri.'-'.$n.'.ics', $this->event($uri, $n, $count, $start));
                    $bar->advance();
                }
            });
        }

        $bar->finish();
        $this->newLine();
    }

    private function seedContacts(User $user, string $uri, int $count): void
    {
        $bookId = (int) DB::table('addressbooks')
            ->where('principaluri', $user->principal_uri)
            ->where('uri', $uri)
            ->value('id');
        $backend = new AddressBookBackend(DB::connection()->getPdo());

        $this->line('Creating '.$count.' contacts…');
        $bar = $this->output->createProgressBar($count);

        foreach (array_chunk(range(1, $count), self::BATCH) as $batch) {
            DB::transaction(function () use ($batch, $backend, $bookId, $uri, $bar): void {
                foreach ($batch as $n) {
                    $backend->createCard($bookId, $uri.'-'.$n.'.vcf', $this->contact($uri, $n));
                    $bar->advance();
                }
            });
        }

        $bar->finish();
        $this->newLine();
    }

    /**
     * Spread over two years around today: every 10th repeats weekly ten times,
     * every 25th is all-day, every 7th has a location and description.
     */
    private function event(string $uri, int $n, int $count, Carbon $start): string
    {
        $day = $start->copy()->addDays(intdiv(($n - 1) * 730, max($count, 1)));
        $begin = $day->copy()->setTime(8 + ($n % 10), ($n % 2) * 30);
        $stamp = Carbon::now('UTC')->format('Ymd\THis\Z');
        $lines = [
            'BEGIN:VCALENDAR',
            'VERSION:2.0',
            'PRODID:-//NexusDAV//seed-test-data//EN',
            'BEGIN:VEVENT',
            'UID:'.$uri.'-event-'.$n.'@nexusdav.test',
            'DTSTAMP:'.$stamp,
            'SUMMARY:Load test event '.$n,
        ];

        if ($n % 25 === 0) {
            $lines[] = 'DTSTART;VALUE=DATE:'.$day->format('Ymd');
            $lines[] = 'DTEND;VALUE=DATE:'.$day->copy()->addDay()->format('Ymd');
        } else {
            $lines[] = 'DTSTART:'.$begin->format('Ymd\THis\Z');
            $lines[] = 'DTEND:'.$begin->copy()->addHour()->format('Ymd\THis\Z');
        }

        if ($n % 10 === 0) {
            $lines[] = 'RRULE:FREQ=WEEKLY;COUNT=10';
        }

        if ($n % 7 === 0) {
            $lines[] = 'LOCATION:Room '.($n % 50 + 1);
            $lines[] = 'DESCRIPTION:Generated for a large-collection sync test.';
        }

        return implode("\r\n", [...$lines, 'END:VEVENT', 'END:VCALENDAR'])."\r\n";
    }

    /**
     * Every 3rd has an organisation, every 20th a photo.
     */
    private function contact(string $uri, int $n): string
    {
        $lines = [
            'BEGIN:VCARD',
            'VERSION:3.0',
            'PRODID:-//NexusDAV//seed-test-data//EN',
            'UID:'.$uri.'-contact-'.$n.'@nexusdav.test',
            'FN:Test Contact '.$n,
            'N:Contact '.$n.';Test;;;',
            'EMAIL;TYPE=INTERNET:contact'.$n.'@example.com',
            'TEL;TYPE=CELL:+1555'.str_pad((string) $n, 7, '0', STR_PAD_LEFT),
        ];

        if ($n % 3 === 0) {
            $lines[] = 'ORG:Example Org '.($n % 40 + 1);
        }

        if ($n % 20 === 0) {
            $lines[] = 'PHOTO;ENCODING=b;TYPE=PNG:'.self::PHOTO;
        }

        return implode("\r\n", [...$lines, 'END:VCARD'])."\r\n";
    }
}
